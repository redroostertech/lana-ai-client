// Regenerates src/text/slugTable.ts from the Swift golden export (fixtures/golden/slug.json).
// Run after `npm run golden:export` from desktop/.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const source = new URL("../../fixtures/golden/slug.json", root);
const target = new URL("src/text/slugTable.ts", root);
const { table } = JSON.parse(readFileSync(source, "utf8"));
const entries = Object.entries(table)
  .map(([hex, value]) => [Number.parseInt(hex, 16), value])
  .sort((a, b) => a[0] - b[0]);
for (const [, value] of entries) {
  if (!/^[a-z0-9-]*$/.test(value)) throw new Error("Unexpected slug table value");
}
const packed = entries.map(([code, value]) => `${code.toString(36)}:${value}`).join(",");
const lines = [
  "// Generated by scripts/generate-slug-table.mjs from the Swift golden export. Do not edit.",
  "//",
  "// For each non-ASCII scalar, what Foundation's diacritic and case folding (en_US_POSIX)",
  "// followed by `lowercased()` leaves of it inside `IdempotencyKey.slug`: an empty string",
  "// means the scalar disappears, ASCII text replaces it. Scalars not listed break words.",
  "// Packed as `codePointBase36:value` pairs.",
  `export const SLUG_TABLE_PACKED = ${JSON.stringify(packed)};`,
  "",
];
writeFileSync(target, lines.join("\n"));
console.log(`slug table: ${entries.length} entries -> ${fileURLToPath(target)}`);
