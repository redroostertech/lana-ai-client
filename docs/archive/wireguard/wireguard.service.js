// src/services/vpn/services/wireguard.service.js
const { execSync, exec } = require('child_process');
const { promisify } = require('util');
const fs = require('fs').promises;
const path = require('path');
const vpnConfig = require('../../../config/vpn.config');
const { logInfo, logError } = require('../../../shared/logging/logger');

const execAsync = promisify(exec);

/**
 * WireGuard Service
 * Handles WireGuard server configuration, key generation, and client config creation
 */
class WireGuardService {
  constructor() {
    this.config = vpnConfig.wireguard;
  }

  /**
   * Check if WireGuard is installed
   * @returns {Promise<boolean>}
   */
  async isInstalled() {
    try {
      await execAsync('which wg');
      return true;
    } catch (error) {
      return false;
    }
  }

  /**
   * Generate a new WireGuard key pair
   * @returns {Promise<{privateKey: string, publicKey: string}>}
   */
  async generateKeyPair() {
    try {
      const privateKey = execSync('wg genkey').toString().trim();
      const publicKey = execSync(`echo "${privateKey}" | wg pubkey`).toString().trim();

      return { privateKey, publicKey };
    } catch (error) {
      logError('Failed to generate WireGuard key pair', error);
      throw new Error('Failed to generate WireGuard keys');
    }
  }

  /**
   * Read server's public key
   * @returns {Promise<string>}
   */
  async getServerPublicKey() {
    try {
      const publicKey = await fs.readFile(this.config.serverPublicKeyPath, 'utf8');
      return publicKey.trim();
    } catch (error) {
      logError('Failed to read server public key', error);
      throw new Error('Server public key not found. Run setup first.');
    }
  }

  /**
   * Read server's private key
   * @returns {Promise<string>}
   */
  async getServerPrivateKey() {
    try {
      const privateKey = await fs.readFile(this.config.serverPrivateKeyPath, 'utf8');
      return privateKey.trim();
    } catch (error) {
      logError('Failed to read server private key', error);
      throw new Error('Server private key not found. Run setup first.');
    }
  }

  /**
   * Initialize WireGuard server (generate keys, create config)
   * @returns {Promise<{serverPublicKey: string, serverPrivateKey: string}>}
   */
  async initializeServer() {
    try {
      logInfo('Initializing WireGuard server...');

      // Check if keys already exist
      let serverPublicKey, serverPrivateKey;
      try {
        serverPublicKey = await this.getServerPublicKey();
        serverPrivateKey = await this.getServerPrivateKey();
        logInfo('Using existing WireGuard server keys');
      } catch (error) {
        // Generate new keys
        logInfo('Generating new WireGuard server keys...');
        const keys = await this.generateKeyPair();
        serverPrivateKey = keys.privateKey;
        serverPublicKey = keys.publicKey;

        // Ensure directory exists
        const keyDir = path.dirname(this.config.serverPrivateKeyPath);
        await fs.mkdir(keyDir, { recursive: true });

        // Save keys
        await fs.writeFile(this.config.serverPrivateKeyPath, serverPrivateKey, { mode: 0o600 });
        await fs.writeFile(this.config.serverPublicKeyPath, serverPublicKey, { mode: 0o644 });

        logInfo('WireGuard server keys generated and saved');
      }

      // Create server config
      await this.createServerConfig(serverPrivateKey);

      return { serverPublicKey, serverPrivateKey };
    } catch (error) {
      logError('Failed to initialize WireGuard server', error);
      throw error;
    }
  }

  /**
   * Create WireGuard server configuration file
   * @param {string} serverPrivateKey
   * @returns {Promise<void>}
   */
  async createServerConfig(serverPrivateKey) {
    const configContent = `# WireGuard Server Configuration
# Generated by LANA-AI VPN Service

[Interface]
Address = ${this.config.serverAddress}
ListenPort = ${this.config.listenPort}
PrivateKey = ${serverPrivateKey}

# Enable IP forwarding (macOS)
# PostUp = sysctl -w net.inet.ip.forwarding=1
# PostDown = sysctl -w net.inet.ip.forwarding=0

# Peers will be added dynamically below
# Use 'wg addconf' or edit this file and restart
`;

    const configDir = path.dirname(this.config.configPath);
    await fs.mkdir(configDir, { recursive: true });
    await fs.writeFile(this.config.configPath, configContent, { mode: 0o600 });

    logInfo(`WireGuard server config created at ${this.config.configPath}`);
  }

  /**
   * Generate client configuration for a user
   * @param {Object} params
   * @param {string} params.userId - User ID
   * @param {string} params.userEmail - User email
   * @param {string} params.clientIp - Assigned VPN IP for this client
   * @param {string} params.clientPrivateKey - Client's private key
   * @param {string} params.clientPublicKey - Client's public key
   * @returns {Promise<string>} Client config content
   */
  async generateClientConfig({ userId, userEmail, clientIp, clientPrivateKey, clientPublicKey }) {
    try {
      const serverPublicKey = await this.getServerPublicKey();

      if (!this.config.publicEndpoint) {
        throw new Error('WIREGUARD_PUBLIC_ENDPOINT not configured. Set this in .env');
      }

      // Build AllowedIPs: VPN subnet + local networks accessible through VPN
      const allowedIPs = [
        this.config.subnet,
        ...this.config.allowedLocalNetworks
      ].join(', ');

      const configContent = `# WireGuard Client Configuration
# User: ${userEmail}
# Generated: ${new Date().toISOString()}

[Interface]
PrivateKey = ${clientPrivateKey}
Address = ${clientIp}/32
DNS = ${this.config.dns.join(', ')}

[Peer]
PublicKey = ${serverPublicKey}
Endpoint = ${this.config.publicEndpoint}
AllowedIPs = ${allowedIPs}
PersistentKeepalive = ${this.config.persistentKeepalive}
`;

      // Save client config to file
      const clientConfigDir = this.config.clientConfigDir;
      await fs.mkdir(clientConfigDir, { recursive: true });

      const clientConfigPath = path.join(clientConfigDir, `${userId}.conf`);
      await fs.writeFile(clientConfigPath, configContent, { mode: 0o600 });

      logInfo(`Client config generated for ${userEmail} at ${clientConfigPath}`);

      return configContent;
    } catch (error) {
      logError('Failed to generate client config', error);
      throw error;
    }
  }

  /**
   * Add a peer to the WireGuard server configuration
   * @param {Object} peer
   * @param {string} peer.publicKey - Client's public key
   * @param {string} peer.allowedIp - Client's VPN IP (e.g., "10.100.0.25/32")
   * @param {string} peer.comment - Comment for the peer
   * @returns {Promise<void>}
   */
  async addPeer({ publicKey, allowedIp, comment }) {
    try {
      const peerConfig = `
# ${comment}
[Peer]
PublicKey = ${publicKey}
AllowedIPs = ${allowedIp}
`;

      // Append to server config
      await fs.appendFile(this.config.configPath, peerConfig);

      logInfo(`Peer added: ${comment}`);

      // Reload WireGuard config if interface is running
      try {
        await execAsync(`wg addconf ${this.config.interfaceName} <(wg-quick strip ${this.config.configPath})`);
        logInfo('WireGuard configuration reloaded');
      } catch (error) {
        logInfo('WireGuard interface not running. Config will be loaded on next start.');
      }
    } catch (error) {
      logError('Failed to add peer', error);
      throw error;
    }
  }

  /**
   * Remove a peer from the WireGuard server configuration
   * @param {string} publicKey - Client's public key to remove
   * @returns {Promise<void>}
   */
  async removePeer(publicKey) {
    try {
      // Read current config
      const configContent = await fs.readFile(this.config.configPath, 'utf8');

      // Remove peer section
      const peerRegex = new RegExp(`\\n# .*\\n\\[Peer\\]\\nPublicKey = ${publicKey}\\nAllowedIPs = .*\\n`, 'g');
      const updatedConfig = configContent.replace(peerRegex, '');

      // Write updated config
      await fs.writeFile(this.config.configPath, updatedConfig, { mode: 0o600 });

      logInfo(`Peer removed: ${publicKey}`);

      // Remove from running interface
      try {
        await execAsync(`wg set ${this.config.interfaceName} peer ${publicKey} remove`);
        logInfo('Peer removed from running interface');
      } catch (error) {
        logInfo('WireGuard interface not running or peer not found.');
      }
    } catch (error) {
      logError('Failed to remove peer', error);
      throw error;
    }
  }

  /**
   * Get next available IP address for a new client
   * @param {Array<string>} existingIps - Array of already allocated IPs
   * @returns {string} Next available IP
   */
  getNextAvailableIp(existingIps = []) {
    const startIp = this.config.clientIpRangeStart;
    const endIp = this.config.clientIpRangeEnd;

    // Simple IP increment logic (assumes /24 subnet)
    const ipParts = startIp.split('.').map(Number);
    const endParts = endIp.split('.').map(Number);

    for (let i = ipParts[3]; i <= endParts[3]; i++) {
      const candidateIp = `${ipParts[0]}.${ipParts[1]}.${ipParts[2]}.${i}`;
      if (!existingIps.includes(candidateIp)) {
        return candidateIp;
      }
    }

    throw new Error('No available IP addresses in the configured range');
  }

  /**
   * Start WireGuard interface
   * @returns {Promise<void>}
   */
  async start() {
    try {
      await execAsync(`wg-quick up ${this.config.interfaceName}`);
      logInfo(`WireGuard interface ${this.config.interfaceName} started`);
    } catch (error) {
      logError('Failed to start WireGuard interface', error);
      throw error;
    }
  }

  /**
   * Stop WireGuard interface
   * @returns {Promise<void>}
   */
  async stop() {
    try {
      await execAsync(`wg-quick down ${this.config.interfaceName}`);
      logInfo(`WireGuard interface ${this.config.interfaceName} stopped`);
    } catch (error) {
      logError('Failed to stop WireGuard interface', error);
      throw error;
    }
  }

  /**
   * Get WireGuard interface status
   * @returns {Promise<Object>}
   */
  async getStatus() {
    try {
      const { stdout } = await execAsync(`wg show ${this.config.interfaceName}`);
      return {
        running: true,
        output: stdout
      };
    } catch (error) {
      return {
        running: false,
        output: null
      };
    }
  }
}

module.exports = new WireGuardService();
